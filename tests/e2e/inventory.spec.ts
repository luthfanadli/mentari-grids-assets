test('power-plant symbols open original footprints and stay independent of grid voltage', async ({ page }) => {
  const errors: string[] = []
  page.on('pageerror', error => errors.push(error.message))
  await page.goto('/')
  await expect(page.getByTestId('plant-count')).toHaveText('633')
  const plants = page.getByRole('checkbox', { name: 'Power plants', exact: true })
  await expect(plants).toBeChecked()
  await plants.uncheck()
  await expect(page.getByTestId('plant-count')).toHaveText('0')
  await plants.check()
  await page.getByRole('checkbox', { name: 'Tagged construction', exact: true }).check()
  await expect(page.getByTestId('plant-count')).toHaveText('643')
  await page.getByRole('checkbox', { name: 'Tagged construction', exact: true }).uncheck()
  await page.getByRole('searchbox').fill('-21724790')
  await expect(page.getByTestId('plant-count')).toHaveText('1')
  const map = page.getByTestId('map')
  await expect(map).toHaveAttribute('data-rendered-plant-symbols', '1')
  const plant = JSON.parse(readFileSync('public/data/power-plants.geojson', 'utf8')).features.find((f: any) => f.properties.source_id === '-21724790')
  const project = (lng: number, lat: number) => [(lng + 180) / 360, (1 - Math.log(Math.tan(Math.PI / 4 + lat * Math.PI / 360)) / Math.PI) / 2]
  const center = project(Number(await map.getAttribute('data-center-lng')), Number(await map.getAttribute('data-center-lat')))
  const marker = project(...plant.properties.plant_representative_point as [number, number])
  const scale = 512 * 2 ** Number(await map.getAttribute('data-zoom'))
  const box = (await map.boundingBox())!
  await page.locator('.maplibregl-canvas').click({ position: { x: box.width / 2 + (marker[0]! - center[0]!) * scale, y: box.height / 2 + (marker[1]! - center[1]!) * scale } })
  await expect(page.getByTestId('asset-details')).toContainText('Power plant footprint')
  await expect(page.getByTestId('asset-details')).toContainText('power_plant')
  await expect(page.getByTestId('asset-details')).toContainText('Unit unspecified')
  await expect(page.getByTestId('asset-details')).toContainText('not verified COD')
  await expect(map).toHaveAttribute('data-substation-mode', 'footprints')
  await expect(map).toHaveAttribute('data-rendered-plant-symbols', '0')
  await expect(page.locator('.viewport-count')).toContainText('1 rendered in viewport')
  await page.getByRole('button', { name: 'Close feature details' }).click()
  for (const voltage of [500, 275, 150, 70]) await page.getByRole('checkbox', { name: `${voltage} kV`, exact: true }).uncheck()
  await expect(page.getByTestId('plant-count')).toHaveText('1')
  await page.getByRole('button', { name: 'Legend', exact: true }).click()
  await expect(page.locator('#map-legend-content')).toContainText('Power plants')
  await expect(page.locator('#map-legend-content')).not.toContainText('Transmission lines')
  await page.getByRole('button', { name: /Change basemap:/ }).click()
  await page.getByRole('radio', { name: 'Plain background', exact: true }).click()
  await expect(map).toHaveAttribute('data-ready', 'true')
  await expect(page.locator('.viewport-count')).toContainText('1 rendered in viewport')
  await expect(page.getByTestId('plant-count')).toHaveText('1')
  expect(errors).toEqual([])
})

test('missing power-plant data retries without losing the base datasets', async ({ page }) => {
  let fail = true, requests = 0
  await page.route('**/data/power-plants.geojson', route => { requests++; return fail ? route.fulfill({ status: 503, body: 'unavailable' }) : route.continue() })
  await page.goto('/')
  await expect(page.getByRole('alert')).toContainText('power-plants.geojson')
  fail = false
  await page.getByRole('button', { name: 'Retry inventory', exact: true }).click()
  await expect(page.getByTestId('plant-count')).toHaveText('633')
  await expect(page.getByTestId('line-count')).toHaveText('4,345')
  expect(requests).toBe(2)
})
