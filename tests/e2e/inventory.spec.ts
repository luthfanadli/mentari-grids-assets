async function openLayers(page: Page, advanced = false) {
  const toggle = page.getByRole('button', { name: 'Layers', exact: true })
  if (await toggle.getAttribute('aria-expanded') !== 'true') await toggle.click()
  const panel = page.getByRole('dialog', { name: 'Map layers', exact: true })
  if (advanced) for (const group of await panel.locator('.layer-filter-group').all()) {
    if (await group.getAttribute('open') === null) await group.locator('summary').click()
  }
  return panel
}
async function setChecked(page: Page, name: string | RegExp, checked: boolean) {
  await openLayers(page, true)
  await page.getByRole('checkbox', { name, exact: typeof name === 'string' }).setChecked(checked)
}
async function resetLayers(page: Page) {
  await openLayers(page)
  await page.getByRole('button', { name: 'Reset', exact: true }).click()
}

