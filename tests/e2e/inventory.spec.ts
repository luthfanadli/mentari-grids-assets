test('overview symbols select original polygon footprints without changing counts', async ({ page }) => {
  await page.goto('/')
  await expect(page.getByTestId('line-count')).toHaveText('4,345')
  await page.getByRole('searchbox').fill('-18678451')
  const map = page.getByTestId('map')
  await expect(map).toHaveAttribute('data-substation-mode', 'representative-symbols')
  await expect(map).toHaveAttribute('data-rendered-symbols', '1')
  await expect(page.getByTestId('primary-count')).toHaveText('1')
  const symbol = displaySymbols.find((f: any) => f.id === 'power_substation_polygon:-18678451')
  const projection = (lng: number, lat: number) => [
    (lng + 180) / 360,
    (1 - Math.log(Math.tan(Math.PI / 4 + lat * Math.PI / 360)) / Math.PI) / 2,
  ]
  const view = projection(Number(await map.getAttribute('data-center-lng')), Number(await map.getAttribute('data-center-lat')))
  const location = projection(...symbol.geometry.coordinates as [number, number])
  const scale = 512 * 2 ** Number(await map.getAttribute('data-zoom'))
  const box = (await map.boundingBox())!
  await page.locator('.maplibregl-canvas').click({ position: { x: box.width / 2 + (location[0]! - view[0]!) * scale, y: box.height / 2 + (location[1]! - view[1]!) * scale } })
  await expect(page.getByTestId('asset-details')).toContainText('GITET Pedan')
  await expect(page.getByTestId('asset-details')).toContainText('Polygon')
  await expect(map).toHaveAttribute('data-substation-mode', 'footprints')
  await expect(map).toHaveAttribute('data-rendered-symbols', '0')
  await expect(page.getByTestId('primary-count')).toHaveText('1')
  await expect(page.locator('.viewport-count')).toContainText('1 rendered in viewport')
})

test('point-only candidates are lazy, retryable, independent and excluded from primary counts', async ({ page }) => {
  let fail = true, requests = 0
  const errors: string[] = []
  page.on('pageerror', error => errors.push(error.message))
  await page.route('**/data/substations-point-candidates.geojson', route => {
    requests++
    return fail ? route.fulfill({ status: 503, body: 'unavailable' }) : route.continue()
  })
  await page.goto('/')
  await expect(page.getByTestId('primary-count')).toHaveText('621')
  expect(requests).toBe(0)
  await page.getByRole('checkbox', { name: /Point-only candidates/ }).check()
  await expect(page.getByRole('alert')).toContainText('substations-point-candidates.geojson')
  fail = false
  await page.getByRole('button', { name: 'Retry point candidates' }).click()
  await expect(page.getByTestId('point-count')).toHaveText(String(summary.datasets.point_candidates.count))
  await expect(page.getByTestId('primary-count')).toHaveText('621')
  await expect(page.getByTestId('review-count')).toHaveText('0')
  await page.getByRole('checkbox', { name: /Point-only candidates/ }).uncheck()
  await page.getByRole('checkbox', { name: /Point-only candidates/ }).check()
  expect(requests).toBe(2)
  await page.getByRole('checkbox', { name: /Transmission lines/ }).uncheck()
  await page.getByRole('checkbox', { name: /Primary substations/ }).uncheck()
  await page.getByRole('checkbox', { name: /Unknown voltage/ }).uncheck()
  await expect(page.getByTestId('point-count')).toHaveText('0')
  await page.getByRole('checkbox', { name: /Unknown voltage/ }).check()
  await page.getByRole('searchbox').fill('4465682088')
  await expect(page.getByTestId('point-count')).toHaveText('1')
  await page.getByRole('button', { name: /Gardu Listrik/ }).click()
  await expect(page.getByTestId('asset-details')).toContainText('Unvalidated point-only candidate')
  await expect(page.getByTestId('asset-details')).toContainText('Not available')
  await expect(page.getByTestId('asset-details')).toContainText('original source location')
  await expect(page.getByTestId('map')).toHaveAttribute('data-rendered-point-candidates', '1')
  await expect(page.locator('.viewport-count')).toContainText('1 rendered in viewport')
  await page.getByRole('button', { name: 'Close feature details' }).click()
  await page.getByRole('searchbox').fill('14305665334')
  await expect(page.getByTestId('point-count')).toHaveText('0')
  await expect(page.getByText('No records match these filters.')).toBeVisible()
  expect(errors).toEqual([])
})

