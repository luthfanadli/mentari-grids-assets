test('Google basemap switch retains filters, camera, overlays and separate attribution', async ({ page }) => {
  const googleRequests: string[] = []
  await page.route('https://mt1.google.com/vt/**', route => { googleRequests.push(route.request().url()); return route.abort() })
  await page.goto('/')
  await expect(page.getByTestId('line-count')).toHaveText('4,345')
  await page.getByRole('checkbox', { name: /Point-only candidates/ }).check()
  await expect(page.getByTestId('point-count')).toHaveText('32')
  await expect(page.locator('.viewport-count')).toContainText('rendered in viewport')
  const map = page.getByTestId('map')
  const before = { zoom: Number(await map.getAttribute('data-zoom')), lng: Number(await map.getAttribute('data-center-lng')), lat: Number(await map.getAttribute('data-center-lat')) }
  await page.getByRole('button', { name: /Change basemap:/ }).click()
  await page.getByRole('radio', { name: 'Google Satellite', exact: true }).click()
  await expect(map).toHaveAttribute('data-basemap', 'google_satellite')
  await expect(map).toHaveAttribute('data-ready', 'true')
  await expect.poll(() => googleRequests.length).toBeGreaterThan(0)
  expect(googleRequests.every(url => /\/vt\/lyrs=s&x=\d+&y=\d+&z=\d+/.test(url))).toBe(true)
  await expect(page.locator('.maplibregl-ctrl-attrib')).toContainText('Basemap: © Google Maps')
  await expect(page.locator('.maplibregl-ctrl-attrib')).toContainText('Inventory: © OpenStreetMap contributors')
  await expect(page.locator('.viewport-count')).toContainText('rendered in viewport')
  expect(Number(await map.getAttribute('data-zoom'))).toBeCloseTo(before.zoom, 5)
  expect(Number(await map.getAttribute('data-center-lng'))).toBeCloseTo(before.lng, 5)
  expect(Number(await map.getAttribute('data-center-lat'))).toBeCloseTo(before.lat, 5)
  await expect(page.getByTestId('line-count')).toHaveText('4,345')
  await expect(page.getByTestId('primary-count')).toHaveText('621')
  await expect(page.getByTestId('point-count')).toHaveText('32')
  await page.getByRole('button', { name: /Change basemap:/ }).click()
  await page.getByRole('radio', { name: 'Plain background', exact: true }).click()
  await expect(map).toHaveAttribute('data-basemap', 'plain')
  await expect(map).toHaveAttribute('data-ready', 'true')
  await expect(page.locator('.viewport-count')).toContainText('rendered in viewport')
  await expect(page.getByTestId('point-count')).toHaveText('32')
  await page.getByRole('button', { name: /Change basemap:/ }).click()
  await page.getByRole('radio', { name: 'OpenStreetMap', exact: true }).click()
  await expect(map).toHaveAttribute('data-basemap', 'osm')
  await expect(map).toHaveAttribute('data-ready', 'true')
  await expect(page.getByTestId('primary-count')).toHaveText('621')
})
